//! macOS launcher confinement: design §10 step 6, the launcher's half
//! (`docs/superpowers/plans/2026-09-18-sandbox-p3-macos.md`, Task 8).
//!
//! The launcher binds the data plane's port, lets the descriptor cross the `execve` the backend
//! performs, and launches this executable again under Seatbelt; [`crate::commands::start::run`]
//! supervises the child it gets back. macOS launches for the same reason Windows does — Linux is
//! the arm that confines in place ([`super::linux::confine_in_place`]) — which is why this
//! returns the [`Child`] and that one returns `()`.
//!
//! **The configuration travels as text, and the launcher never builds a `Config` from a host path
//! the child cannot reach** (decision 18): the child re-derives every answer from the payload's
//! text, the environment and its inherited argv, and the file itself may sit outside every
//! exposure.
//!
//! **The launcher owns `state`, and here the reason is the token rather than an unwritable
//! file.** The secret that guards `/status` and `/stop` is generated by the process that
//! publishes it, so this arm mints it, puts it on the launch payload for the child to adopt, and
//! writes the file once the child reports it is listening; [`crate::commands::start::run`] takes
//! the file back on `supervise`'s teardown, guarded by the pid it names — which is this
//! process's, because the `--daemon` parent's readiness check compares that pid against the one
//! it spawned. The child never writes it either way: `serve` publishes only where
//! `adopted.is_none()`, and a launched child is never that process.
//!
//! **Three things differ from the Windows arm beside this one**, and each is a property of the
//! platform rather than of the shape:
//!
//! - **There is no AppContainer, so the child runs as the user.** Seatbelt changes no identity
//!   and holds no capability set (design §8; decision 11 is Linux's), so nothing here has to hand
//!   a channel over for an *identity* reason — but the local management channel is handed over
//!   all the same, for the profile's reason: a unix `bind()` is a network operation, and the
//!   profile grants none, so a child that bound its own control socket would die with
//!   `Operation not permitted`. This process binds the socket outside the sandbox, clears
//!   `FD_CLOEXEC` on it, and the child adopts the descriptor — the data plane's listener handoff,
//!   applied to the control channel (decision 16). The token is still the launcher's, and it
//!   travels on the same plan: this process publishes the file the child's plane verifies against.
//! - **The listener still has to cross `execve`.** A descriptor does not inherit across the exec
//!   by default, so this arm clears `FD_CLOEXEC` on the sockets it hands over — the backend does
//!   it for the socket the plan owns, and this arm for the control channel's, which no plan
//!   owns — and what reaches the child is the descriptor an argv element names, which the child
//!   rebuilds through the facade's `adopted_listener` and `adopted_control`. The port is
//!   therefore *this* process's bind, which is what lets **serving** spend no network grant at
//!   all (decision 16): the rendered profile carries no network rule of any kind, and
//!   `a_confined_server_serves_a_request_and_forwards_its_child_status` is the run that proves
//!   it for both channels.
//! - **There is no job object.** Windows ties the child's lifetime to the launcher's with
//!   `JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE`; Seatbelt has no analogue, so a launcher killed with
//!   `SIGKILL` leaves the confined server behind. That is an accepted gap, recorded in the plan's
//!   Self-Review, and it is why the stop path forwards a signal instead of relying on the
//!   launcher's death to end the child. **A failed `state` publish used to be the same gap's
//!   other road, and it is closed**: the publish is the last fallible step with a child already
//!   serving, and `confine_or_launch` now ends and reaps that child before returning the publish
//!   error ([`retract`], on the platform `SIGKILL` `Child::kill` answers with). The accepted gap
//!   is unchanged rather than narrowed away — it is the launcher that dies *without* running that
//!   code, which no code in this process can cover. What the pre-flight still buys is the
//!   realistic arrival at a directory that cannot take the entry: [`refuse_unwritable_state_dir`]
//!   refuses it *before* anything is confined, so the remaining window is a directory that changes
//!   between that probe and the publish, and that window is now a killed child rather than a
//!   serving one.

// The two levels [`retract`] needs, and only it: the launch's own events belong to the platform
// crate (`info!` for what a confinement was, `debug!` for the detail behind it, shared §7), so this
// arm logs nothing of its own on the success path.
#[cfg(feature = "api")]
use tracing::{error, info};

use super::{launch::Handoff, refuse_unwritable_state_dir};
#[cfg(feature = "api")]
use crate::_api::{
    bind::bind_unix,
    state as api_state,
    transport::{LocalForm, resolve_socket_path},
};
use crate::{
    // **The two names the shared surface does not carry** — the `Options` this arm builds from the
    // resolved mechanism, and the backend that takes them — are the platform's own vocabulary and
    // are imported here rather than into `super`. The seam (`crate::sandbox`) names no platform
    // crate, which is what its module doc promises and what this arm's copy of `launcher_backend`
    // keeps true: the mechanism is resolved, logged and taken to a backend in the one file that is
    // *this* platform's, and no other arm reads the variable at all.
    _sandbox::macos::{Backend as MacosBackend, Options as MacosOptions},
    // The trait as an anonymous binding, because its one method is called on the
    // concrete backend `launcher_backend` builds and the *name* `Backend` would
    // shadow nothing here but read as if this arm had chosen a type (the Linux arm
    // imports the trait by name because it names the type too). `Confinement` is
    // deliberately not among these: this arm hands `backend.confine`'s answer
    // straight to `super::launch::supervised`, which is where the one outcome a
    // launcher may not serve through is refused.
    _sandbox::{Backend as _, Child, ControlHandle},
    Error,
    commands::start::{Args, api_options},
    resolve::Resolution,
};

/// Design §10 step 6 on macOS: the exposure set, the payload, the bound listener and the launch.
///
/// **The mode is the resolved one**, not `[server] read_only`: `TINIO_READ_ONLY` and `--read-only`
/// are part of the chain that produced it, so reading the document here would expose the served
/// root read-write on a run the operator asked to be read-only.
///
/// **The exposure set is the platform-neutral one and this arm adds nothing to it.** In particular
/// there is **no executable-directory grant**: decision 22 scopes that ACE to Windows, where a
/// confined child genuinely cannot load without it, while on macOS `process-exec` is the only gate
/// and a read of the child's own image is refused and logged without stopping the program (the
/// plan's Task 2 records the measurement). A reader who arrives here to "fix" the missing grant
/// should re-read that decision rather than add it.
///
/// **The listener is bound here rather than by the child** (decision 16): the child inherits a
/// socket instead of the right to bind, which is what lets the profile drop that rule, and the
/// descriptor reaches it in argv. **The local management control socket is bound here for the
/// same reason**, and that is the change that lets the profile drop the rule entirely: a unix
/// `bind()` is a network operation, the grant that covered it permitted binding anything rather
/// than filtering to the one socket the child wants, and the child therefore adopts a socket this
/// process bound instead of making its own (the data plane's handoff, applied to the control
/// channel).
///
/// **The token is generated here when the run has a local management channel**, with the channel
/// it guards: `api_options` is the CLI's one definer of the selection, so the launcher and the
/// child cannot disagree about whether a local channel exists, and the file this process writes
/// names the channel this process bound. A run with no local channel (`--api http://…`, or a build
/// without `api`) hands nothing over and owns no `state` file.
///
/// # Errors
///
/// The bind, the token generation, the publish's half-connected pair, the probe of the `state`
/// directory, the `state` publish, and every failure the backend reports — each fatal, because a
/// confinement that cannot be applied must not leave the process running unconfined
/// (design §11). **A publish that fails after the child is running is the one failure that already
/// has a process to answer for**, and it is answered rather than returned through: [`retract`]
/// kills the child with the platform's own `SIGKILL` ([`Child::kill`]) and reaps it
/// ([`Child::wait`]) before this function returns the publish error — so the operator sees the
/// `state` failure, and no confined server is left listening with nothing naming it. Windows needs
/// none of that: its dropped `Child` closes the job that owns the process (decision 20). **The
/// accepted gap is not this path and is unchanged**: it is a launcher killed outright, which runs
/// no code here. **Nor is this the first thing a bad state directory meets**:
/// [`refuse_unwritable_state_dir`] is called in the control-channel arm, before the channel is
/// bound — the bind is itself the first thing to touch the state directory, since a unix socket is
/// a file in it — and it refuses a read-only, full or missing state directory while no child
/// exists. What is left for this path is a directory that changed between that probe and the
/// publish, and such a directory now costs a killed child rather than an orphaned server.
pub(super) fn confine_or_launch(resolution: &Resolution, args: &Args) -> Result<Child, Error> {
    let (sandbox, plan) = super::launch::prepare(resolution)?;
    // **The control channel, when this run has a local one.** Bound here — outside the sandbox,
    // where the bind is permitted — because the confined child may not bind it, and handed over the
    // way the Windows arm hands its pipe over: the descriptor number on the plan, the token the
    // child verifies against beside it. Held to the end of this function and no further: what keeps
    // the socket alive is the child's own inherited descriptor, and this process never serves on it.
    #[cfg(feature = "api")]
    let control = {
        let selection = api_options(resolution, args)?;
        match selection.local {
            Some(LocalForm::Unix(path)) => {
                // **The publish's precondition, proved while no child exists to serve without it.**
                // This arm **is** the publish's condition — a local channel is bound here and the
                // token that guards it is minted two lines down, which is the pair the publish at
                // the end of this function reads — so a run that never publishes (`--api http://…`,
                // `--no-api-unix`) takes the `_` arm below and pays nothing here.
                //
                // **It sits above the bind, and that placement is load-bearing rather than
                // tidy.** The unix socket is a file *in the state directory*, so `bind_unix` is the
                // first thing to touch it and it is where a read-only or missing directory would
                // fail — with a message about a socket and an `EPERM`, which is the shape
                // `refuse_underived_state_dir`'s doc records as unusable. Probing first is what
                // turns that into a refusal that names the directory and the remedy, and it leaves
                // no bound socket behind. `refuse_unwritable_state_dir`'s doc owns why the refusal
                // is here at all and what window it leaves open; `start::run`'s step h created the
                // directory before any confinement, so the probe never mints one.
                refuse_unwritable_state_dir(&resolution.state_dir)
                    .map_err(|err| Error::Operational(err.to_string()))?;
                // The path through the one definer of the relative→state-dir rule, which is also
                // what the child's `Plane::adopt` applies — so the socket this binds and the
                // identity that plane records are one path rather than two derivations of one.
                let channel = bind_unix(&resolve_socket_path(&path, &resolution.state_dir))?;
                // The token the child will verify against, generated here because this is the
                // process that publishes the file it guards.
                let token = api_state::generate_token()?;
                // **The plan carries an owned duplicate, and that is what separates this half of
                // the handoff from the clear.** `try_clone_to_owned` answers a descriptor
                // `F_DUPFD_CLOEXEC` already made close-on-exec, so this launcher keeps every flag
                // on the socket it bound and nothing here calls `fcntl`; the platform crate is
                // then free to clear the *plan's* descriptor at the one moment that matters, after
                // the pre-flight it owns and before the real spawn. While the plan carried a bare
                // `i64` the clear had nowhere to happen but here, ahead of the pre-flight, and the
                // probe's two processes (`sandbox-exec` plus the `/bin/echo` it execs) inherited a
                // listening socket they had no business holding — measured on macOS 15.8,
                // 2026-09-25, the pre-flight's process held `fd 3`, this socket. The child still
                // receives the descriptor its argv element names — the launcher's half is the
                // duplicate, and the integer→descriptor rebuild is one of the platform crate's
                // three enumerated `unsafe` sites, the child's half.
                let plan = plan
                    .with_control(ControlHandle::duplicate(channel.socket())?)
                    .with_token(token);
                (plan, Some(channel))
            }
            // No local channel: an `http://`/`https://` selection, or `--no-api-unix`. The child
            // serves no local channel at all, and this process owns no `state` file for one.
            _ => (plan, None),
        }
    };
    #[cfg(not(feature = "api"))]
    let control = (plan, None);
    let (plan, _channel) = control;
    // **The publish's one value, built here and once** — `Handoff`'s own doc owns why the two
    // halves are one fact and what it refuses. It is built **before the launch** so a
    // half-connected pair is a startup refusal rather than a serving child whose `state` file was
    // never written, and it borrows the token off the plan rather than holding a second copy of it.
    #[cfg(feature = "api")]
    let handoff = Handoff::of(&plan, _channel.as_ref())?;
    // **The mechanism comes from the environment, through this arm's own
    // `launcher_backend`** — the one place the platform's options are built and the
    // resolved mechanism logged ([`launcher_backend`], whose doc owns why the refusal
    // is a usage error). One resolution, and the whole launch follows it: the render,
    // the check and the spawn all read that value, so a run cannot render for one
    // mechanism and check with the other. **The child does not re-read the variable**
    // — the resolved mechanism rides the launch payload — so that line is the only
    // reader in either process.
    let mut backend = launcher_backend()?;
    // `mut`: the publish's failure arm is the one place this function has to *act* on the child
    // after handing it over, and `Child::kill` is what it acts with.
    let mut child = super::launch::supervised("macOS", backend.confine(&sandbox, &plan)?)?;
    // **The publish, once the child says it is listening.** The token comes back off the plan and
    // the control name off the channel rather than out of second copies — the handoff above is
    // that pair and nothing else — so the value in the payload the child adopted, the name the
    // child's plane records and the value in the file are one value and one name by construction.
    // **It is the last fallible step with a child already running**, so its failure arm ends the
    // child before returning it ([`retract`]) — the contract that a startup failure leaves no
    // serving process behind. A run that bound no local channel has no handoff, and no `state`
    // file is owed for one: that is a state of the launch rather than a half of the pair.
    #[cfg(feature = "api")]
    if let Some(handoff) = &handoff
        && let Err(error) = super::launch::publish_state(&child, handoff, resolution)
    {
        retract(&mut child);
        return Err(error);
    }
    Ok(child)
}

/// End the confined child a failed launch step left behind, and reap it — **reporting nothing**,
/// because the caller already holds the error the operator has to see.
///
/// **This is the launch-failure path's child half, and the reason it is a function rather than
/// two lines at the call site is that both outcomes have to be *logged* rather than propagated or
/// dropped.** The `Child` dropped by returning that error would end nothing on this platform: the
/// Seatbelt-confined server would keep the port it was handed and there would be no `state` file,
/// so `tinio status` and `tinio stop` could not find it and nothing would name it (the module doc's
/// third platform note). [`Child::kill`] is the platform's `SIGKILL`, and [`Child::wait`] is what
/// **reaps** — a killer that only ends a process leaves a zombie, and this child's own stdout is
/// already at EOF, so the wait returns rather than blocking on a relay that has nothing left to
/// read. **Either outcome of either call stays out of the return**: the caller reports the publish
/// error unchanged, because "the state file could not be written" is the operator's problem and
/// "the child that was serving could not be signalled" is the diagnosis attached to it.
#[cfg(feature = "api")]
fn retract(child: &mut Child) {
    let ended = child.kill();
    // The wait runs on both arms: after a successful kill it is the reap, and after a failed one it
    // is what tells us the child's own status instead of leaving the value unwaited.
    let reaped = match child.wait() {
        Ok(status) => Some(status.code()),
        Err(error) => {
            error!(step = "retract", error = %error, "the reaping wait failed");
            None
        }
    };
    match ended {
        Ok(()) => info!(
            step = "retract",
            code = ?reaped,
            "the child of a failed launch was killed and reaped"
        ),
        Err(error) => error!(
            step = "retract",
            error = %error,
            code = ?reaped,
            "the child of a failed launch could not be killed: it may still be serving, and the \
             publish failure is what the operator sees"
        ),
    }
}

// The `state` publish — its readiness gate, the bound it waits on and the pid/name choice — is
// `super::launch`'s, shared with the Windows arm rather than spelled here.

/// The backend for this platform, built with the options only its own crate carries — **the one
/// reader of `TINIO_SANDBOX_MACOS_MECHANISM` in either process**, and the arm's rather than the
/// seam's.
///
/// **It lives here because it is this platform's vocabulary and no other arm's** (design decision
/// 2): `super` is the seam three channels collapse in, it builds no backend and names no platform
/// crate, so the mechanism is resolved, logged and taken to a backend in the one file that is this
/// platform's — the shape the child's own half of the same decision has, in
/// `super::apply_self_confinement`. Windows has nothing to configure and reaches the facade's
/// `platform()`; Linux builds its options inline because `enter` reads two further facts off them.
///
/// **One resolution, and the whole launch follows it**: the render, the pre-flight check and the
/// spawn all read the value this returns, so a run cannot render for one mechanism and check with
/// the other. The child does not re-read the variable — the resolved mechanism rides the launch
/// payload — so this is the only reader in either process.
///
/// # Errors
///
/// The platform's own refusal for a value it does not know: a
/// `TINIO_SANDBOX_MACOS_MECHANISM` that is neither `sandbox-exec` nor `sandbox-init`, which is a
/// **usage** error naming the variable and both values.
fn launcher_backend() -> Result<MacosBackend, Error> {
    // The refusal is the platform's and it becomes a **usage** error here, because
    // the operator's shell is where the wrong value was typed. The platform answers
    // `Error::Unsupported`, which this crate frames as a startup failure (exit 1) —
    // the wrong exit code for a bad environment value, and the reason the
    // conversion is explicit rather than a `?`.
    let options = MacosOptions::from_env().map_err(|err| Error::Usage(err.to_string()))?;
    // The one line that records the choice before anything acts on it: an operator
    // reading a failed startup has to be able to tell which mechanism ran, and a
    // `debug!` would be invisible under `serve`'s fixed `Verbosity::Info`.
    tracing::info!(
        step = "mechanism",
        mechanism = %options.mechanism(),
        "the macOS confinement mechanism is resolved"
    );
    Ok(MacosBackend::with_options(options))
}
